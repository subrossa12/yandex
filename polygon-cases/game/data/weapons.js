  /* Скруглённый прямоугольник как подконтур. */
  function rr(x, y, w, h, r) {
    r = Math.min(r, w / 2, h / 2);
    return 'M' + (x + r) + ' ' + y +
      'L' + (x + w - r) + ' ' + y + 'Q' + (x + w) + ' ' + y + ' ' + (x + w) + ' ' + (y + r) +
      'L' + (x + w) + ' ' + (y + h - r) + 'Q' + (x + w) + ' ' + (y + h) + ' ' + (x + w - r) + ' ' + (y + h) +
      'L' + (x + r) + ' ' + (y + h) + 'Q' + x + ' ' + (y + h) + ' ' + x + ' ' + (y + h - r) +
      'L' + x + ' ' + (y + r) + 'Q' + x + ' ' + y + ' ' + (x + r) + ' ' + y + 'Z';
  }

  /* Круг четырьмя кривыми — без дуг, чтобы рамка считалась по числам. */
  function circle(cx, cy, r) {
    var k = r * 1.02;
    return 'M' + (cx - r) + ' ' + cy +
      'Q' + (cx - r) + ' ' + (cy - k) + ' ' + cx + ' ' + (cy - r) +
      'Q' + (cx + r) + ' ' + (cy - k) + ' ' + (cx + r) + ' ' + cy +
      'Q' + (cx + r) + ' ' + (cy + k) + ' ' + cx + ' ' + (cy + r) +
      'Q' + (cx - r) + ' ' + (cy + k) + ' ' + (cx - r) + ' ' + cy + 'Z';
  }

  /* Ряд продольных прорезей: перфорация цевья, вентиляция кожуха. */
