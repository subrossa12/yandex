  /*
   * Габаритная рамка модели. Нужна, чтобы вписать предмет в кадр:
   * пистолет и винтовка нарисованы в одной системе координат, но занимают
   * в ней очень разное место, и без подгонки пистолет в сетке инвентаря
   * выглядел бы огрызком в углу пустой карточки.
   *
   * Координаты вынимаются прямо из путей. Контрольные точки кривых при
   * этом тоже попадают в расчёт, и рамка выходит чуть шире фактической —
   * для кадрирования это только на пользу, лишний воздух не мешает.
   */
  var NUM = /-?\d+(?:\.\d+)?/g;

  function measure(w) {
    var minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;

    w.parts.forEach(function (p) {
      var nums = p.d.match(NUM) || [];
      for (var i = 0; i + 1 < nums.length; i += 2) {
        var x = parseFloat(nums[i]), y = parseFloat(nums[i + 1]);
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    });

    var pad = 7;
    w.box = {
      x: minX - pad, y: minY - pad,
      w: (maxX - minX) + pad * 2, h: (maxY - minY) + pad * 2
    };
    return w;
  }

  /* ------------------------------------------------------------------ *
   * ПРОФИЛЬ
   *
   * Главное, чем нарисованное оружие отличается от набросанного, —
   * пропорции. На референсах ствольная коробка занимает по высоте
   * примерно седьмую часть длины: вещь длинная и низкая. Нарисованная
   * «на глаз» геометрия всегда выходит выше и короче, и предмет
   * читается как игрушка, сколько деталей на него ни навешивай.
   *
   * Чинить это правкой каждой координаты бессмысленно: мелкая механика
   * (перфорация, рёбра) считается генераторами и разъехалась бы с
   * корпусом. Поэтому профиль приводится один раз и сразу ко всему —
   * сжатием по вертикали относительно ствольной линии и лёгким
   * растяжением по горизонтали.
   *
   * Кадрирование потом вписывает результат в карточку, так что предмет
   * не становится мельче — он становится длиннее.
   * ------------------------------------------------------------------ */
  var PROFILE = { bore: 46, squashY: 0.7, stretchX: 1.08, originX: 8 };

  function fx(x) { return Math.round((PROFILE.originX + (x - PROFILE.originX) * PROFILE.stretchX) * 100) / 100; }
  function fy(y) { return Math.round((PROFILE.bore + (y - PROFILE.bore) * PROFILE.squashY) * 100) / 100; }

  /*
   * Пересчёт координат в пути. Во всех командах, которые здесь
   * используются (M, L, C, Q), числа идут строго парами x,y — поэтому
   * достаточно чередовать преобразование. Ради этого в путях и запрещены
   * дуги и сокращённые команды: у них порядок другой.
   */
  function reshape(d) {
    var i = 0;
    return d.replace(/-?\d+(?:\.\d+)?/g, function (m) {
      var v = parseFloat(m);
      var out = (i % 2 === 0) ? fx(v) : fy(v);
      i++;
      return String(out);
    });
  }

